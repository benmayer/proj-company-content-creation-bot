"""Show the same request before and after reviewer feedback (card 19 evidence).

Run from the repo root:  python evidence/self_learning_demo.py [--mock]

Uses a throwaway feedback file, so the real ``outputs/`` store is untouched.
Writes ``evidence/self_learning/comparison.md``. Without ``--mock`` it calls the
configured LLM twice; if that fails it says so and falls back to the mock, where
only the prompt (not the draft) can differ.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import sys
import tempfile

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src.content_pipeline import ContentPipeline, ContentRequest  # noqa: E402
from src.feedback_store import FeedbackStore, FileBackend  # noqa: E402
from src.llm_integration import LLMError, generate_draft  # noqa: E402

OUTPUT = ROOT / "evidence" / "self_learning" / "comparison.md"

REQUEST = ContentRequest(
    content_type="social_post",
    product="flights",
    topic="reply: a customer complaining about cabin bag rules",
    channel="X",
    original_content="Another airline, another fight over my cabin bag. Why is this so hard?",
    post_type="reply",
)

# Illustrative reviewer decisions seeded for the demo. They are style feedback, not company facts.
SEEDED_APPROVED = "Bag drama? Pack light, board happy. See you at the gate. ✈️"
SEEDED_DECLINE_REASON = "Too corporate and too long. X replies must be one or two short, playful lines with no formal sign-off."


def _mock(prompt: str, client: object = None) -> str:
    return "Mock draft (the mock LLM ignores the prompt).\n\nHUMAN REVIEW NOTES\n- Verify wording."


def _generate(prompt: str, use_mock: bool) -> tuple:
    if not use_mock:
        try:
            return generate_draft(prompt), "real LLM"
        except (LLMError, RuntimeError) as exc:
            print(f"Real LLM unavailable ({exc}); falling back to the mock.")
    return _mock(prompt), "mock LLM (draft text cannot change; compare the prompts)"


def _learned_block(prompt: str) -> str:
    section = prompt.split("LEARNED FEEDBACK — ")[1].split("FORMAT LIMITS")[0]
    return section.split("\n", 1)[1].strip()  # drop the rest of the heading line


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--mock", action="store_true", help="Skip real LLM calls.")
    args = parser.parse_args()

    with tempfile.TemporaryDirectory() as directory:
        store = FeedbackStore(FileBackend(Path(directory) / "feedback.jsonl"))
        pipeline = ContentPipeline(output_dir=directory, feedback_store=store)
        context = pipeline.monitor(REQUEST)

        before_prompt = pipeline.brief(REQUEST, context)
        before_draft, mode = _generate(before_prompt, args.mock)

        store.record("approved", REQUEST.channel, REQUEST.feedback_type, REQUEST.product, REQUEST.topic, SEEDED_APPROVED)
        store.record("declined", REQUEST.channel, REQUEST.feedback_type, REQUEST.product, REQUEST.topic,
                     "Dear valued customer, we sincerely apologise for any inconvenience ...", SEEDED_DECLINE_REASON)

        after_prompt = pipeline.brief(REQUEST, context)
        after_draft, _ = _generate(after_prompt, args.mock or mode.startswith("mock"))

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(
        "# Self-learning: same request before and after feedback\n\n"
        f"Generated by `evidence/self_learning_demo.py` using the {mode}.\n\n"
        "## Request (identical both times)\n\n"
        f"- Channel: {REQUEST.channel}\n- Type: {REQUEST.post_type}\n- Product: {REQUEST.product}\n"
        f"- Topic: {REQUEST.topic}\n- Original post: {REQUEST.original_content}\n\n"
        "## Feedback recorded in between\n\n"
        f"- Approved draft: {SEEDED_APPROVED}\n- Declined, reason: {SEEDED_DECLINE_REASON}\n\n"
        "These are illustrative reviewer decisions, not company facts. Only the decline reason is fed back.\n\n"
        "## Before: learned-feedback block in the prompt\n\n"
        f"```\n{_learned_block(before_prompt)}\n```\n\n"
        "## After: learned-feedback block in the prompt\n\n"
        f"```\n{_learned_block(after_prompt)}\n```\n\n"
        f"## Draft before feedback\n\n```\n{before_draft.strip()}\n```\n\n"
        f"## Draft after feedback\n\n```\n{after_draft.strip()}\n```\n",
        encoding="utf-8",
    )
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({mode})")


if __name__ == "__main__":
    main()
